/** Flat deduplicated list of every word in the vocabulary treasury. */
export const allVocabulary = [...new Set(Object.values(vocabulary).flat())]

function pickDistinct<T>(pool: readonly T[], count: number, random: () => number): T[] {
  const copy = [...pool]
  const out: T[] = []
  const n = Math.min(count, copy.length)
  for (let i = 0; i < n; i++) {
    const j = i + Math.floor(random() * (copy.length - i))
    ;[copy[i], copy[j]] = [copy[j]!, copy[i]!]
    out.push(copy[i]!)
  }
  return out
}

/**
 * Draws a small, cross-domain tray of concrete words, skipping any words (or
 * their stems, including compound parts) that are currently resting or worn deep.
 */
export function drawVocabulary({
  avoid = [],
  count = 9,
  random = Math.random,
}: {
  avoid?: readonly string[]
  count?: number
  random?: () => number
} = {}): string[] {
  const blocked = new Set(
    avoid.flatMap((w) => (w.toLowerCase().match(/[a-z']+/g) ?? []).map(stemOf)),
  )
  const allowed = (word: string) =>
    (word.toLowerCase().match(/[a-z']+/g) ?? []).every((part) => !blocked.has(stemOf(part)))
  const domains = pickDistinct(Object.values(vocabulary), Object.keys(vocabulary).length, random)
  const picked: string[] = []
  const seen = new Set<string>()
  for (const domain of domains) {
    if (picked.length >= count) break
    const fresh = domain.filter((word) => !seen.has(word) && allowed(word))
    if (!fresh.length) continue
    const word = fresh[Math.floor(random() * fresh.length)]!
    seen.add(word)
    picked.push(word)
  }
  if (picked.length < count) {
    const rest = allVocabulary.filter((word) => !seen.has(word) && allowed(word))
    picked.push(...pickDistinct(rest, count - picked.length, random))
  }
  return picked
}

/** Concise guidance inviting the mind to reach for fresh physical words without forcing them. */
export function vocabularyNote(words: readonly string[]): string {
  if (!words.length) return ''
  return ` Fresh concrete words at hand (use one or two if they fit, or let them spark others; favour sharp physical detail over vague poetic fillers): ${words.join(', ')}.`
}
